const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const index = read('web/index.html');
const updater = read('web/update-center.js');
const main = read('android/app/src/main/java/com/animeweek/tracker/MainActivity.java');
const installer = read('android/app/src/main/java/com/animeweek/tracker/UpdateInstaller.java');
const backupBridge = read('android/app/src/main/java/com/animeweek/tracker/BackupBridge.java');
const notificationWorker = read('android/app/src/main/java/com/animeweek/tracker/UpdateCheckWorker.java');
const manifest = read('android/app/src/main/AndroidManifest.xml');
const gradle = read('android/app/build.gradle');
const paths = read('android/app/src/main/res/xml/file_paths.xml');
const latest = JSON.parse(read('latest.json'));
const pkg = JSON.parse(read('package.json'));
const webManifest = JSON.parse(read('web/manifest.webmanifest'));
const themeNames = ['aurora','violet','ocean','sunset','gold','mono','halloween','christmas','newyear','valentines','spring','dayofdead'];

assert.match(index, /<script src="update-center\.js"><\/script>/, 'web app loads the update center');
assert.match(index, /<\/body>\s*<\/html>\s*$/, 'document has a single final HTML close');
assert.match(index, /nativeBridge\.saveJson\(safeName,json,requestId\)/, 'Android backup passes its confirmation callback ID');
assert.match(backupBridge, /saveJson\(String filename, String json, String callbackId\)/, 'native backup bridge accepts the confirmation callback ID');
assert.match(backupBridge, /callback\(\{success:/, 'native backup bridge confirms completion to the web app');
assert.match(index, /appBrandLogoImage/, 'theme-aware brand logo is present');
assert.match(index, /v95-29-festive-wallpaper-and-theme-logos/, 'festive background wallpaper is present');
assert.ok(updater.includes("APP_VERSION = '95.30.1'"), 'updater reports the current app version');
assert.match(updater, /raw\.githubusercontent\.com/, 'updater reads the GitHub manifest');
assert.match(updater, /AndroidUpdateInstaller\.downloadAndInstall/, 'updater calls the native Android installer');
assert.match(main, /"AndroidUpdateInstaller"/, 'MainActivity exposes the native update bridge');
assert.match(installer, /setLauncherTheme/, 'native bridge can switch the launcher icon with the selected theme');
assert.ok(installer.includes('95.30.1'), 'native updater fallback version is current');
assert.match(manifest, /LauncherAurora/, 'Android has a default theme launcher alias');
assert.match(manifest, /LauncherHalloween/, 'Android includes festive launcher aliases');
assert.ok(manifest.includes('@drawable/animeweek_icon_crop_aurora'), 'Android launcher uses the cropped original Aurora emblem');
assert.ok(manifest.includes('@drawable/animeweek_icon_crop_dayofdead'), 'Android launcher uses the cropped original Day of the Dead emblem');
assert.match(gradle, /copyAnimeWeekThemeIcons/, 'Gradle copies theme emblems into Android drawable resources');
assert.ok(gradle.includes('web/assets/theme-icons'), 'Android resources come from the original web theme artwork');
assert.ok(index.includes("const iconUrl=festiveThemeAssets[id]||'assets/theme-icons/aurora.webp'"), 'header and favicon use original theme WebP artwork');
assert.ok(index.includes('v95-30-theme-surface-cohesion'), 'theme palettes style app backgrounds and cards');
assert.ok(index.includes('v95-30-1-logo-edge-cleanup'), 'header logo rim is cropped without changing the original art');
assert.ok(index.includes('app-brand-logo img'), 'header logo crop styles are present');
assert.ok(manifest.includes('android.permission.POST_NOTIFICATIONS'), 'Android declares the notification permission');
assert.match(installer, /enableUpdateNotifications/, 'native bridge can enable update notifications');
assert.match(installer, /disableUpdateNotifications/, 'native bridge can disable update notifications');
assert.match(installer, /areUpdateNotificationsEnabled/, 'native bridge reports notification preference state');
assert.match(notificationWorker, /PeriodicWorkRequestBuilder/, 'background update checks use WorkManager');
assert.match(notificationWorker, /12, TimeUnit.HOURS/, 'background update checks run approximately every 12 hours');
assert.match(notificationWorker, /NotificationCompat\.Builder/, 'background update worker posts Android notifications');
assert.match(notificationWorker, /last_notified_version_code/, 'background update worker avoids duplicate notifications');
assert.ok(updater.includes('Activar avisos automáticos'), 'update center offers notification opt-in');
assert.ok(updater.includes('Desactivar avisos automáticos'), 'update center offers notification opt-out');
assert.equal(webManifest.icons[0].src, 'assets/theme-icons/aurora.webp');
assert.equal(webManifest.icons[0].type, 'image/webp');
for (const theme of themeNames) {
  assert.ok(fs.existsSync(path.join(root, 'web/assets/theme-icons', theme + '.webp')), 'original theme art exists: ' + theme);
  assert.ok(manifest.includes('@drawable/animeweek_icon_crop_' + theme), 'Android launcher alias uses a cropped icon: ' + theme);
  const croppedIcon = read('android/app/src/main/res/drawable/animeweek_icon_crop_' + theme + '.xml');
  assert.ok(croppedIcon.includes('android:insetLeft="-3dp"'), 'launcher icon removes outer edge: ' + theme);
}

assert.match(installer, /SHA-256/, 'native updater validates SHA-256');
assert.match(installer, /getApkContentsSigners/, 'native updater verifies the APK signer');
assert.match(installer, /getInstalledVersion/, 'native updater reports installed version to web UI');
assert.match(installer, /getLongVersionCode/, 'native updater rejects old versionCode');
assert.match(manifest, /REQUEST_INSTALL_PACKAGES/, 'app declares package-install permission');
assert.match(paths, /external-files-path/, 'FileProvider exposes private downloaded APKs');
assert.match(gradle, /9530001/, 'native versionCode has been advanced');
assert.equal(pkg.version, '95.30.1');
assert.equal(latest.appId, 'com.animeweek.tracker');
assert.equal(latest.version, '95.30.0');
assert.equal(latest.android.enabled, true, 'the verified v95.30.0 Android Release is enabled');
assert.equal(latest.android.versionCode, 9530000);
assert.ok(latest.android.apkUrl.endsWith('/app-release.apk'), 'latest manifest URL matches the actual Release APK asset');
assert.ok(latest.android.apkUrl.includes('/v95.30.0/'), 'latest manifest points to the official v95.30.0 APK');
console.log('Update center integration checks passed.');
